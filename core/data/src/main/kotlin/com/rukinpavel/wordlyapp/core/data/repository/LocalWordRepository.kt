    // Unchanged signature — existing callers (ViewModel, etc.) keep working exactly as before.
    override suspend fun getRandomWord(language: Language): String {
        val words =
            when (language) {
                Language.EN -> enWords
                Language.RU -> ruWords
                Language.UK -> uaWords
            }.filter { it.word.length == 5 }

        if (words.isEmpty()) return ""

        return words[Random.nextInt(words.size)].word
    }

    /**
     * Additive helper — does not touch the interface or any existing caller.
     * Call it with the word returned by getRandomWord() to get its hint.
     * Returns null if that word doesn't have a hint yet.
     */
    override suspend fun getHint(word: String, language: Language): String? {
        val words =
            when (language) {
                Language.EN -> enWords
                Language.RU -> ruWords
                Language.UK -> uaWords
            }

        return words.firstOrNull { it.word == word }?.hint
    }
